export interface ProfessionalSeed {
  /** Used both as the user id and the professional profile id. */
  id: string;
  firstName: string;
  lastName: string;
  businessName: string;
  avatarUrl: string | null;
  headline: string;
  bio: string;
  categoryIds: CategoryId[];
  /** Categories used for the generated job history (defaults to `categoryIds`). */
  historyCategoryIds?: CategoryId[];
  yearsOfExperience: number;
  base: { placeId: string; streetIndex: number; houseNumber: number };
  radiusKm: number;
  phone: string;
  email: string;
  website: string | null;
  licenseNumber: string | null;
  isInsured: boolean;
  languages: string[];
  startingPrice: number | null;
  isVerified: boolean;
  memberSinceDaysAgo: number;
  availability: WeeklyAvailability;
  /** Number of generated historical completed jobs. */
  historyJobs: number;
  isDemo: boolean;
  demoDescription: string | null;
}

type Hours = readonly [string, string];

function weekly(hours: Partial<Record<Weekday, Hours>>, acceptsEmergencyCalls = false): WeeklyAvailability {
  const days = Object.fromEntries(
    WEEKDAYS.map((day) => {
      const range = hours[day];
      return [day, range ? { enabled: true, start: range[0], end: range[1] } : { enabled: false, start: '09:00', end: '17:00' }];
    }),
  ) as WeeklyAvailability['days'];
  return { days, acceptsEmergencyCalls };
}

const workWeek = (start: string, end: string, friday: Hours | null = ['08:00', '13:00']) => ({
  sun: [start, end] as Hours,
  mon: [start, end] as Hours,
  tue: [start, end] as Hours,
  wed: [start, end] as Hours,
  thu: [start, end] as Hours,
  ...(friday ? { fri: friday } : {}),
});

